"""Builds the web-ready wallpaper assets in public/scene/ from the source art in art/.

    python scripts/build-scene-assets.py

- background.png  -> background.webp
                     underwater-mask.svg (from SURFACE, the traced bottom edge of the water surface)
- dolphin.png     -> dolphin.webp (trimmed)
- fish/*.png      -> fish/*.webp (trimmed)
- bubbles.png     -> bubbles/bubble-1..7.webp (the single bubbles in the sheet's top row)
- dylan-gum.jpg   -> public/dylan.webp (the avatar; already square, so only scaled down)
- homepage/**     -> public/homepage/**/<name>.webp (1400px) + <name>-thumb.webp (400px), for the
                     Interests site; EXIF (incl. GPS) is dropped. Reference them in src/data/homepage.ts.
- Steam headers   -> public/homepage/games/steam-<appId>.jpg for every appId in src/data/homepage.ts
- icons/*.png     -> public/icons/<name>.webp, 256x256 (trimmed, centred on a square). The full-size
                     generated icons live in art/icons/; reference the .webp in src/data/apps.ts etc.

The cut-outs have faint near-transparent specks left over from background removal; those are
cleared so each sprite trims to its real bounds (and compresses far better).
"""

import re
import urllib.request
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "art"
OUT = ROOT / "public" / "scene"

SPECK_ALPHA = 20  # alpha below this is background-removal dust
TRIM_ALPHA = 40  # bounds are measured on pixels at least this opaque
PAD = 6


def clean(im: Image.Image) -> Image.Image:
    arr = np.array(im.convert("RGBA"))
    arr[arr[:, :, 3] < SPECK_ALPHA] = 0
    return Image.fromarray(arr)


def trim(im: Image.Image) -> Image.Image:
    alpha = np.array(im)[:, :, 3]
    ys, xs = np.where(alpha >= TRIM_ALPHA)
    box = (
        max(0, xs.min() - PAD),
        max(0, ys.min() - PAD),
        min(im.width, xs.max() + PAD + 1),
        min(im.height, ys.max() + PAD + 1),
    )
    return im.crop(box)


def fit(im: Image.Image, longest: int) -> Image.Image:
    scale = longest / max(im.size)
    if scale >= 1:
        return im
    return im.resize((round(im.width * scale), round(im.height * scale)), Image.LANCZOS)


def save(im: Image.Image, path: Path, quality: int = 86) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    im.save(path, "WEBP", quality=quality, method=6)
    print(f"{path.relative_to(ROOT)}  {im.width}x{im.height}  {path.stat().st_size // 1024} KB")


def sprite(src: Path, dest: Path, longest: int) -> None:
    save(fit(trim(clean(Image.open(src))), longest), dest)


def bubbles(src: Path, dest_dir: Path) -> None:
    """Slice the top row of the sheet into single bubbles, split on empty columns."""
    sheet = clean(Image.open(src))
    row = sheet.crop((0, 0, sheet.width, 254))  # the first empty band starts at y=254
    solid = np.array(row)[:, :, 3] > 120
    cols = solid.any(axis=0)
    spans, start = [], None
    for x, filled in enumerate(list(cols) + [False]):
        if filled and start is None:
            start = x
        elif not filled and start is not None:
            if x - start > 8:
                spans.append((start, x))
            start = None
    for i, (x0, x1) in enumerate(spans, 1):
        cell = row.crop((max(0, x0 - PAD), 0, min(row.width, x1 + PAD), row.height))
        save(fit(trim(cell), 160), dest_dir / f"bubble-{i}.webp")


# Bottom edge of the painted water surface in background.png (x, y in image pixels), traced by eye.
# Fish and bubbles are masked to the area below it. Re-trace this when the background changes.
SURFACE = [
    (0, 467), (100, 472), (200, 478), (300, 488), (400, 498), (500, 510), (600, 520), (700, 530),
    (800, 540), (900, 548), (1000, 555), (1100, 558), (1200, 556), (1300, 548), (1400, 525),
    (1500, 515), (1600, 505), (1700, 495), (1800, 485), (1916, 476),
]
SURFACE_MARGIN = 18  # px below the edge, so the feathered mask never shows anything above it


def underwater_mask(width: int, height: int, dest: Path) -> None:
    pts = " ".join(f"L{x} {y + SURFACE_MARGIN}" for x, y in SURFACE)
    first, last = SURFACE[0][1] + SURFACE_MARGIN, SURFACE[-1][1] + SURFACE_MARGIN
    d = f"M-40 {height + 80} L-40 {first} {pts} L{width + 40} {last} L{width + 40} {height + 80} Z"
    dest.write_text(
        f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" preserveAspectRatio="none">
  <!-- Generated by scripts/build-scene-assets.py: the area below the painted water surface. -->
  <filter id="feather" x="-5%" y="-5%" width="110%" height="110%"><feGaussianBlur stdDeviation="7"/></filter>
  <path filter="url(#feather)" fill="#fff" d="{d}"/>
</svg>
''',
        encoding="utf8",
    )
    print(f"{dest.relative_to(ROOT)}")


# The avatar photo, and an optional square crop in image pixels (None = use the whole image).
# Alternatives kept in art/: dylan.jpg with (360, 0, 1720, 1360); dylan-bubbles.jpg with (360, 40, 992, 672).
AVATAR_SRC = "dylan-gum.jpg"
AVATAR_BOX = None


def avatar(src: Path, dest: Path) -> None:
    im = Image.open(src).convert("RGB")
    if AVATAR_BOX:
        im = im.crop(AVATAR_BOX)
    im = im.resize((256, 256), Image.LANCZOS)
    save(im, dest, quality=88)


PHOTO_TYPES = {".jpg", ".jpeg", ".png", ".webp", ".heic"}


def homepage_photos(src_dir: Path, dest_dir: Path) -> None:
    """Every photo under art/homepage/ becomes a large WebP plus a thumbnail, same folders.

    Only RGB pixels are saved, so camera EXIF (including GPS location) never reaches the site.
    Photos are rotated upright from their EXIF orientation first.
    """
    from PIL import ImageOps

    for path in sorted(src_dir.rglob("*")):
        if path.suffix.lower() not in PHOTO_TYPES:
            continue
        rel = path.relative_to(src_dir).with_suffix("")
        out = dest_dir / rel
        im = ImageOps.exif_transpose(Image.open(path)).convert("RGB")
        save(fit(im, 1400), out.with_name(out.name + ".webp"), quality=82)
        save(fit(im, 400), out.with_name(out.name + "-thumb.webp"), quality=80)


ICON_SIZE = 256
ICON_MARGIN = 0.03  # breathing room on each side, as a share of the icon


def app_icons(src_dir: Path, dest_dir: Path) -> None:
    """Each generated icon is cleaned, trimmed to its real bounds and centred on a square,
    so icons from different generations come out the same visual size."""
    for path in sorted(src_dir.glob("*.png")):
        im = trim(clean(Image.open(path)))
        side = round(max(im.size) / (1 - 2 * ICON_MARGIN))
        square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
        square.paste(im, ((side - im.width) // 2, (side - im.height) // 2))
        save(square.resize((ICON_SIZE, ICON_SIZE), Image.LANCZOS), dest_dir / f"{path.stem}.webp", quality=90)


def steam_headers(data_file: Path, dest_dir: Path) -> None:
    """Download each Steam header image once, so the site doesn't hotlink Steam."""
    ids = sorted(set(re.findall(r"appId:\s*(\d+)", data_file.read_text(encoding="utf8"))))
    for app_id in ids:
        dest = dest_dir / f"steam-{app_id}.jpg"
        if dest.exists():
            continue
        url = f"https://cdn.cloudflare.steamstatic.com/steam/apps/{app_id}/header.jpg"
        dest.parent.mkdir(parents=True, exist_ok=True)
        req = urllib.request.Request(url, headers={"User-Agent": "dylanweicker.github.io asset build"})
        with urllib.request.urlopen(req, timeout=30) as res:
            dest.write_bytes(res.read())
        print(f"{dest.relative_to(ROOT)}  {dest.stat().st_size // 1024} KB")


def main() -> None:
    bg = Image.open(SRC / "background.png").convert("RGB")
    save(bg, OUT / "background.webp", quality=92)
    underwater_mask(bg.width, bg.height, OUT / "underwater-mask.svg")
    sprite(SRC / "dolphin.png", OUT / "dolphin.webp", 360)
    for fish in sorted((SRC / "fish").glob("*.png")):
        sprite(fish, OUT / "fish" / f"{fish.stem}.webp", 400)
    bubbles(SRC / "bubbles.png", OUT / "bubbles")
    avatar(SRC / AVATAR_SRC, ROOT / "public" / "dylan.webp")
    if (SRC / "homepage").exists():
        homepage_photos(SRC / "homepage", ROOT / "public" / "homepage")
    steam_headers(ROOT / "src" / "data" / "homepage.ts", ROOT / "public" / "homepage" / "games")
    if (SRC / "icons").exists():
        app_icons(SRC / "icons", ROOT / "public" / "icons")


if __name__ == "__main__":
    main()
